#!/usr/bin/env node
/* ==========================================================================
   AutoCare Pro — single-file builder
   ==========================================================================

   Produces AutoCare-Pro.html: one self-contained HTML file with every
   stylesheet, every script and Chart.js inlined, plus the favicon embedded as
   a data URI. That file can be double-clicked and it just runs — no server, no
   install, no internet.

   Run it whenever you change the source:

       node build-single-file.js

   What it does
   ------------
   1. reads index.html
   2. swaps each <link rel="stylesheet" href="css/…"> for <style>…</style>
   3. swaps each <script src="…"> for <script>…</script>
   4. embeds the favicon as a data: URI and drops the manifest link
      (a manifest and a service worker cannot work from file://)
   5. sets window.AC.STANDALONE = true so app.js skips SW registration

   The multi-file project stays the source of truth; this is a distributable
   copy of it.
   ========================================================================== */

const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const OUT = path.join(ROOT, "AutoCare-Pro.html");

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");

/**
 * A literal "</script>" inside inlined JavaScript would close the tag early.
 * Escaping the slash is invisible to the parser but safe inside the element.
 */
const guard = (code) => code.replace(/<\/script>/gi, "<\\/script>");

function main() {
  let html = read("index.html");

  /* ---------------------------------------------------------- stylesheets */
  let cssCount = 0;
  html = html.replace(
    /[ \t]*<link rel="stylesheet" href="(css\/[^"]+)"\s*\/?>\n?/g,
    (_, href) => {
      cssCount += 1;
      return `  <style>\n/* ===== ${href} ===== */\n${read(href)}\n  </style>\n`;
    }
  );

  /* -------------------------------------------------------------- scripts */
  let jsCount = 0;
  html = html.replace(
    /[ \t]*<script src="([^"]+)"><\/script>\n?/g,
    (_, src) => {
      jsCount += 1;
      return `  <script>\n/* ===== ${src} ===== */\n${guard(read(src))}\n  </script>\n`;
    }
  );

  /* -------------------------------------------------- icons & PWA plumbing */
  const favicon = fs.readFileSync(path.join(ROOT, "assets/icons/favicon-32.png")).toString("base64");
  html = html
    .replace(/[ \t]*<link rel="manifest"[^>]*>\n?/g, "")
    .replace(
      /[ \t]*<link rel="icon"[^>]*>\n?/g,
      `  <link rel="icon" type="image/png" href="data:image/png;base64,${favicon}" />\n`
    )
    .replace(/[ \t]*<link rel="apple-touch-icon"[^>]*>\n?/g, "");

  /* --------------------------------------------------- standalone marker */
  html = html.replace(
    "<!-- Chart.js is vendored locally so the app works offline and needs no CDN -->",
    "<!-- Single-file build: every stylesheet and script is inlined below. -->\n" +
      "  <script>window.AC = window.AC || {}; window.AC.STANDALONE = true;</script>"
  );

  html = html.replace(
    "<title>AutoCare Pro — Smart Vehicle Maintenance System</title>",
    "<title>AutoCare Pro — Smart Vehicle Maintenance System</title>\n" +
      `  <!-- Single-file build generated by build-single-file.js on ${new Date().toISOString()} -->`
  );

  fs.writeFileSync(OUT, html, "utf8");

  const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
  console.log(`AutoCare-Pro.html written — ${cssCount} stylesheets, ${jsCount} scripts, ${kb} KB`);
  if (/<link rel="stylesheet" href="css\//.test(html) || /<script src="js\//.test(html)) {
    console.error("WARNING: some references were not inlined. Check index.html formatting.");
    process.exitCode = 1;
  }
}

main();
